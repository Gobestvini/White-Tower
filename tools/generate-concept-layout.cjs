// Coordinates and raster identities shared with the layered Figma imports.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const screens = JSON.parse(fs.readFileSync(path.join(root, 'docs/art/concepts/facebook-casual/assembled/manifest.json'), 'utf8'));
const rules = ['/* Generated by tools/generate-concept-layout.cjs. Geometry is in the 941 × 1672 Figma frame. */'];
const pct = (n, total) => `${(n / total * 100).toFixed(6)}%`;
const url = file => `url('../assets/ui/facebook-casual/${file}')`;
function slot(selector, screen, name, raster = true) {
  const e = screens.find(s => s.screen === screen).elements.find(e => e.name === name);
  if (!e) throw Error(`${screen}/${name}`);
  rules.push(`${selector} { position:absolute; left:${pct(e.x,941)}; top:${pct(e.y,1672)}; width:${pct(e.width,941)}; height:${pct(e.height,1672)}; ${raster ? `background-image:${url(e.file)};` : ''} }`);
}
function plate(selector, name, x,y,w,h) {
  rules.push(`${selector} { position:absolute; left:${pct(x,941)}; top:${pct(y,1672)}; width:${pct(w,941)}; height:${pct(h,1672)}; background:${url(`panels/panel-${name}.png`)} center / 100% 100% no-repeat; }`);
}
for (const [state, screen] of [['gameplay','01-gameplay'],['tutorial','02-tutorial'],['hint','03-hint'],['victory','06-victory'],['campaign','07-campaign-complete']]) {
  const prefix = `main[data-screen="${state}"]`;
  for (const [selector,name] of [['.settings-button','Button-settings'],['.restart-button','Button-restart'],['.hud-undo','Button-undo'],['.hud-hint','Button-hint']]) {
    if (screens.find(s=>s.screen===screen).elements.some(e=>e.name===name)) slot(`${prefix} .hud ${selector}`,screen,name);
  }
  const logo = screens.find(s=>s.screen===screen).elements.find(e=>e.name==='Logo');
  if(logo) {
    slot(`${prefix} .game-logo`,screen,'Logo',false);
    rules.push(`${prefix} .game-logo { content:${url(logo.file)}; }`);
  }
  if(state==='tutorial') {
    slot(`${prefix} .hud::before`,screen,'HUD');
    slot(`${prefix} .tutorial-tip`,screen,'Tutorial-card');
  }
  if(['gameplay','hint','victory'].includes(state)) {
    if(state!=='victory') slot(`${prefix} .hud-counter`,screen,'Counter');
    slot(`${prefix} .hud-level`,screen,'Level-label',false);
  }
}
